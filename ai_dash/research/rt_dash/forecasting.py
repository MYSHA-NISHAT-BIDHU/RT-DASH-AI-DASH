"""Leakage-controlled thesis-style resource forecasting for RT-DASH.

The thesis resource columns are synthetic simulation annotations.  This module
therefore treats them as a reproducible forecasting benchmark and never as
physical CPU/memory/storage/network measurements.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path

import numpy as np
import pandas as pd


RESOURCE_NAMES = ("CPU", "Memory", "Storage", "Bandwidth")


@dataclass(frozen=True)
class ResourceForecastDataset:
    timestamps: np.ndarray
    values: np.ndarray
    activities: np.ndarray
    sequence_ids: np.ndarray
    splits: np.ndarray
    resource_names: tuple[str, ...] = RESOURCE_NAMES
    interval_seconds: int = 60

    def mask(self, split: str) -> np.ndarray:
        if split not in {"train", "validation", "test"}:
            raise ValueError(f"unknown split: {split}")
        return self.splits == split


@dataclass(frozen=True)
class ForecastExamples:
    x: np.ndarray
    y: np.ndarray
    target_indices: np.ndarray
    splits: np.ndarray

    def mask(self, split: str) -> np.ndarray:
        return self.splits == split


def audit_resource_source(csv_path: str | Path) -> dict[str, object]:
    frame = pd.read_csv(csv_path, usecols=["timestamp", "Activity", *RESOURCE_NAMES])
    converted = {
        column: pd.to_numeric(frame[column], errors="coerce")
        for column in ("Activity", *RESOURCE_NAMES)
    }
    timestamp = pd.to_datetime(frame["timestamp"], format="mixed", errors="coerce")
    return {
        "source_rows": int(len(frame)),
        "invalid_timestamp_rows": int(timestamp.isna().sum()),
        "missing_activity_rows": int(converted["Activity"].isna().sum()),
        "rows_missing_any_resource": int(
            np.column_stack([converted[name].isna().to_numpy() for name in RESOURCE_NAMES])
            .any(axis=1)
            .sum()
        ),
        "missing_by_resource": {
            name: int(converted[name].isna().sum()) for name in RESOURCE_NAMES
        },
        "resource_provenance": "synthetic annotations generated by thesis preprocessing",
    }


def prepare_resource_forecast_dataset(
    csv_path: str | Path, interval_seconds: int = 60
) -> ResourceForecastDataset:
    if interval_seconds <= 0:
        raise ValueError("interval_seconds must be positive")
    frame = pd.read_csv(
        csv_path,
        usecols=["timestamp", "Activity", *RESOURCE_NAMES],
    )
    timestamp = pd.to_datetime(frame["timestamp"], format="mixed", errors="coerce")
    if timestamp.isna().any():
        raise ValueError("processed thesis resource table contains invalid timestamps")
    frame = frame.assign(timestamp=timestamp).sort_values("timestamp", kind="stable")
    for column in (*RESOURCE_NAMES, "Activity"):
        frame[column] = pd.to_numeric(frame[column], errors="coerce")
    # The archived thesis table has one truncated terminal row with no resource
    # annotations.  It cannot be a forecasting target, so drop it rather than
    # fabricating an interpolation.  The thesis preprocessor also omitted the
    # `leisure` activity mapping; treat those labels as non-critical `other` for
    # scheduler integration while leaving the resource series untouched.
    frame = frame.dropna(subset=list(RESOURCE_NAMES)).copy()
    frame["Activity"] = frame["Activity"].fillna(4)

    indexed = frame.set_index("timestamp")
    rule = f"{interval_seconds}s"
    resources = indexed[list(RESOURCE_NAMES)].resample(rule).mean()
    activity_last = indexed["Activity"].resample(rule).last()
    anomaly = (indexed["Activity"] == 5).astype(np.uint8).resample(rule).max()
    combined = resources.copy()
    combined["Activity"] = np.where(anomaly.fillna(0).to_numpy() > 0, 5, activity_last)
    combined = combined.dropna(subset=[*RESOURCE_NAMES, "Activity"])
    if combined.empty:
        raise ValueError("resource resampling produced no usable intervals")

    timestamps = combined.index.to_numpy(dtype="datetime64[s]")
    seconds = timestamps.astype("datetime64[s]").astype(np.int64)
    discontinuity = np.r_[True, np.diff(seconds) != interval_seconds]
    sequence_ids = np.cumsum(discontinuity).astype(np.int64) - 1
    dates = timestamps.astype("datetime64[D]")
    unique_dates = np.array(sorted(np.unique(dates)))
    if len(unique_dates) < 14:
        raise ValueError("expected at least 14 distinct thesis resource dates")
    train_dates = unique_dates[:8]
    validation_dates = unique_dates[8:11]
    test_dates = unique_dates[11:14]
    splits = np.full(len(combined), "purged", dtype="U10")
    splits[np.isin(dates, train_dates)] = "train"
    splits[np.isin(dates, validation_dates)] = "validation"
    splits[np.isin(dates, test_dates)] = "test"

    return ResourceForecastDataset(
        timestamps=timestamps,
        values=combined.loc[:, RESOURCE_NAMES].to_numpy(dtype=np.float64),
        activities=combined["Activity"].to_numpy(dtype=np.int16),
        sequence_ids=sequence_ids,
        splits=splits,
        interval_seconds=interval_seconds,
    )


def make_forecast_examples(
    dataset: ResourceForecastDataset, lookback: int = 12
) -> ForecastExamples:
    if lookback < 2:
        raise ValueError("lookback must be at least two intervals")
    xs: list[np.ndarray] = []
    ys: list[np.ndarray] = []
    indices: list[int] = []
    splits: list[str] = []
    for target in range(lookback, len(dataset.values)):
        source = slice(target - lookback, target + 1)
        if np.any(dataset.sequence_ids[source] != dataset.sequence_ids[target]):
            continue
        split = str(dataset.splits[target])
        if split not in {"train", "validation", "test"}:
            continue
        xs.append(dataset.values[target - lookback : target])
        ys.append(dataset.values[target])
        indices.append(target)
        splits.append(split)
    return ForecastExamples(
        x=np.asarray(xs, dtype=np.float64),
        y=np.asarray(ys, dtype=np.float64),
        target_indices=np.asarray(indices, dtype=np.int64),
        splits=np.asarray(splits, dtype="U10"),
    )


@dataclass(frozen=True)
class TrainStandardizer:
    mean: np.ndarray
    scale: np.ndarray

    @classmethod
    def fit(cls, values: np.ndarray) -> "TrainStandardizer":
        mean = np.mean(values, axis=0)
        scale = np.std(values, axis=0, ddof=0)
        scale = np.where(scale < 1e-12, 1.0, scale)
        return cls(mean.astype(float), scale.astype(float))

    def transform(self, values: np.ndarray) -> np.ndarray:
        return (np.asarray(values, dtype=float) - self.mean) / self.scale

    def inverse_transform(self, values: np.ndarray) -> np.ndarray:
        return np.asarray(values, dtype=float) * self.scale + self.mean


class ARIMA510:
    """ARIMA(5,1,0) using conditional least squares on first differences.

    With q=0, ARIMA(5,1,0) is an AR(5) model of the first-differenced series.
    This implementation avoids adding an external statsmodels dependency while
    retaining the stated statistical model exactly.
    """

    def __init__(self, p: int = 5) -> None:
        if p <= 0:
            raise ValueError("AR order must be positive")
        self.p = int(p)
        self.coefficients: np.ndarray | None = None

    def fit(self, values: np.ndarray, sequence_ids: np.ndarray | None = None) -> "ARIMA510":
        values = np.asarray(values, dtype=float).reshape(-1)
        if sequence_ids is None:
            sequence_ids = np.zeros(len(values), dtype=np.int64)
        sequence_ids = np.asarray(sequence_ids)
        if len(values) != len(sequence_ids):
            raise ValueError("values and sequence_ids length mismatch")
        design: list[list[float]] = []
        target: list[float] = []
        for index in range(self.p + 1, len(values)):
            start = index - self.p - 1
            if np.any(sequence_ids[start : index + 1] != sequence_ids[index]):
                continue
            current_difference = values[index] - values[index - 1]
            lagged = [
                values[index - lag] - values[index - lag - 1]
                for lag in range(1, self.p + 1)
            ]
            design.append([1.0, *lagged])
            target.append(float(current_difference))
        if len(target) <= self.p + 1:
            raise ValueError("not enough contiguous observations for ARIMA fit")
        matrix = np.asarray(design, dtype=float)
        vector = np.asarray(target, dtype=float)
        self.coefficients = np.linalg.lstsq(matrix, vector, rcond=None)[0]
        return self

    def forecast(self, history: np.ndarray, steps: int = 1) -> np.ndarray:
        if self.coefficients is None:
            raise RuntimeError("ARIMA model must be fitted before forecasting")
        if steps <= 0:
            raise ValueError("forecast steps must be positive")
        history_values = list(np.asarray(history, dtype=float).reshape(-1))
        if len(history_values) < self.p + 1:
            raise ValueError("insufficient ARIMA history")
        output = []
        for _ in range(steps):
            differences = np.diff(np.asarray(history_values[-(self.p + 1) :], dtype=float))
            lagged = differences[::-1][: self.p]
            predicted_difference = float(
                self.coefficients[0] + np.dot(self.coefficients[1:], lagged)
            )
            next_value = history_values[-1] + predicted_difference
            history_values.append(next_value)
            output.append(next_value)
        return np.asarray(output, dtype=float)


def fit_arima_models(
    dataset: ResourceForecastDataset,
) -> tuple[ARIMA510, ...]:
    train = dataset.mask("train")
    return tuple(
        ARIMA510().fit(dataset.values[train, column], dataset.sequence_ids[train])
        for column in range(dataset.values.shape[1])
    )


def arima_predict_examples(
    models: tuple[ARIMA510, ...], examples: ForecastExamples
) -> np.ndarray:
    predictions = np.empty_like(examples.y, dtype=float)
    for row, window in enumerate(examples.x):
        for column, model in enumerate(models):
            predictions[row, column] = model.forecast(window[:, column], steps=1)[0]
    return predictions


def exponentially_weighted_history_prediction(
    examples: ForecastExamples, alphas: float | np.ndarray
) -> np.ndarray:
    """Forecast the next vector from causal exponentially weighted histories.

    ``alphas`` may be a single fixed smoothing coefficient or one coefficient
    per resource.  No target value is used by this forecast.
    """

    alpha = np.asarray(alphas, dtype=float)
    if alpha.ndim == 0:
        alpha = np.full(examples.x.shape[2], float(alpha), dtype=float)
    if alpha.shape != (examples.x.shape[2],):
        raise ValueError("alphas must be scalar or one value per resource")
    if np.any((alpha <= 0.0) | (alpha > 1.0)):
        raise ValueError("exponential smoothing alpha must be in (0, 1]")
    state = examples.x[:, 0, :].astype(float).copy()
    for step in range(1, examples.x.shape[1]):
        state = alpha * examples.x[:, step, :] + (1.0 - alpha) * state
    return state


class RidgeVARRegressor:
    """Closed-form ridge regression over a flattened multivariate history."""

    def __init__(self, ridge: float = 1e-2) -> None:
        if ridge < 0.0:
            raise ValueError("ridge penalty must be non-negative")
        self.ridge = float(ridge)
        self.coefficients: np.ndarray | None = None

    def fit(self, x: np.ndarray, y: np.ndarray) -> "RidgeVARRegressor":
        x = np.asarray(x, dtype=float)
        y = np.asarray(y, dtype=float)
        if x.ndim != 3 or y.ndim != 2 or len(x) != len(y):
            raise ValueError("expected x=(samples,time,features), y=(samples,outputs)")
        design = x.reshape(len(x), -1)
        design = np.column_stack([design, np.ones(len(design), dtype=float)])
        penalty = np.eye(design.shape[1], dtype=float) * self.ridge
        penalty[-1, -1] = 0.0  # do not regularize the intercept
        gram = design.T @ design + penalty
        self.coefficients = np.linalg.solve(gram, design.T @ y)
        return self

    def predict(self, x: np.ndarray) -> np.ndarray:
        if self.coefficients is None:
            raise RuntimeError("ridge-VAR model must be fitted before prediction")
        x = np.asarray(x, dtype=float)
        if x.ndim != 3:
            raise ValueError("expected x=(samples,time,features)")
        design = np.column_stack(
            [x.reshape(len(x), -1), np.ones(len(x), dtype=float)]
        )
        return design @ self.coefficients


def select_convex_blend_weights(
    actual: np.ndarray,
    arima_prediction: np.ndarray,
    lstm_prediction: np.ndarray,
    grid: np.ndarray | None = None,
) -> np.ndarray:
    """Select per-resource LSTM weights using the supplied validation data."""

    actual = np.asarray(actual, dtype=float)
    arima_prediction = np.asarray(arima_prediction, dtype=float)
    lstm_prediction = np.asarray(lstm_prediction, dtype=float)
    if not (actual.shape == arima_prediction.shape == lstm_prediction.shape):
        raise ValueError("actual and prediction arrays must have identical shapes")
    if grid is None:
        grid = np.linspace(0.0, 1.0, 21)
    grid = np.asarray(grid, dtype=float)
    if grid.ndim != 1 or len(grid) == 0 or np.any((grid < 0.0) | (grid > 1.0)):
        raise ValueError("blend grid must be a non-empty one-dimensional subset of [0,1]")
    selected = np.empty(actual.shape[1], dtype=float)
    for column in range(actual.shape[1]):
        losses = []
        for weight in grid:
            prediction = (
                (1.0 - weight) * arima_prediction[:, column]
                + weight * lstm_prediction[:, column]
            )
            losses.append(float(np.sqrt(np.mean((prediction - actual[:, column]) ** 2))))
        selected[column] = float(grid[int(np.argmin(losses))])
    return selected


def convex_blend_predictions(
    arima_prediction: np.ndarray,
    lstm_prediction: np.ndarray,
    lstm_weights: np.ndarray,
) -> np.ndarray:
    arima_prediction = np.asarray(arima_prediction, dtype=float)
    lstm_prediction = np.asarray(lstm_prediction, dtype=float)
    weights = np.asarray(lstm_weights, dtype=float)
    if arima_prediction.shape != lstm_prediction.shape:
        raise ValueError("ARIMA and LSTM predictions must have identical shapes")
    if weights.shape != (arima_prediction.shape[1],):
        raise ValueError("one blend weight is required per resource")
    if np.any((weights < 0.0) | (weights > 1.0)):
        raise ValueError("blend weights must lie in [0,1]")
    return (1.0 - weights) * arima_prediction + weights * lstm_prediction


def _sigmoid(values: np.ndarray) -> np.ndarray:
    values = np.clip(values, -30.0, 30.0)
    return 1.0 / (1.0 + np.exp(-values))


class NumpyLSTMRegressor:
    """Small deterministic multivariate LSTM with BPTT and Adam.

    It is deliberately dependency-light so the thesis LSTM remains executable
    in the reproducibility environment without TensorFlow/PyTorch.
    """

    def __init__(
        self,
        input_size: int = 4,
        hidden_size: int = 16,
        output_size: int = 4,
        seed: int = 20260806,
    ) -> None:
        self.input_size = int(input_size)
        self.hidden_size = int(hidden_size)
        self.output_size = int(output_size)
        self.seed = int(seed)
        rng = np.random.default_rng(seed)
        x_scale = np.sqrt(1.0 / max(1, input_size))
        h_scale = np.sqrt(1.0 / max(1, hidden_size))
        self.parameters: dict[str, np.ndarray] = {
            "Wx": rng.normal(0.0, x_scale, size=(input_size, 4 * hidden_size)),
            "Wh": rng.normal(0.0, h_scale, size=(hidden_size, 4 * hidden_size)),
            "b": np.zeros(4 * hidden_size, dtype=float),
            "Wy": rng.normal(0.0, h_scale, size=(hidden_size, output_size)),
            "by": np.zeros(output_size, dtype=float),
        }
        # Positive forget bias improves stable memory at initialization.
        self.parameters["b"][hidden_size : 2 * hidden_size] = 1.0

    def _forward(self, x: np.ndarray, cache: bool = False):
        batch, steps, _ = x.shape
        hidden = np.zeros((batch, self.hidden_size), dtype=float)
        cell = np.zeros_like(hidden)
        states = []
        Wx, Wh, b = self.parameters["Wx"], self.parameters["Wh"], self.parameters["b"]
        H = self.hidden_size
        for step in range(steps):
            previous_hidden = hidden
            previous_cell = cell
            z = x[:, step, :] @ Wx + previous_hidden @ Wh + b
            gate_i = _sigmoid(z[:, :H])
            gate_f = _sigmoid(z[:, H : 2 * H])
            gate_o = _sigmoid(z[:, 2 * H : 3 * H])
            gate_g = np.tanh(z[:, 3 * H :])
            cell = gate_f * previous_cell + gate_i * gate_g
            hidden = gate_o * np.tanh(cell)
            if cache:
                states.append(
                    (x[:, step, :], previous_hidden, previous_cell, gate_i, gate_f, gate_o, gate_g, cell)
                )
        output = hidden @ self.parameters["Wy"] + self.parameters["by"]
        return (output, states) if cache else output

    def _loss_and_gradients(self, x: np.ndarray, target: np.ndarray):
        prediction, states = self._forward(x, cache=True)
        error = prediction - target
        loss = float(np.mean(error**2))
        batch, outputs = target.shape
        d_output = 2.0 * error / (batch * outputs)
        gradients = {name: np.zeros_like(value) for name, value in self.parameters.items()}
        final_hidden = (
            states[-1][5] * np.tanh(states[-1][7])
            if states
            else np.zeros((batch, self.hidden_size))
        )
        gradients["Wy"] = final_hidden.T @ d_output
        gradients["by"] = np.sum(d_output, axis=0)
        d_hidden = d_output @ self.parameters["Wy"].T
        d_cell_next = np.zeros_like(d_hidden)
        H = self.hidden_size
        for state in reversed(states):
            x_t, previous_hidden, previous_cell, gate_i, gate_f, gate_o, gate_g, cell = state
            tanh_cell = np.tanh(cell)
            d_gate_o = d_hidden * tanh_cell
            d_cell = d_hidden * gate_o * (1.0 - tanh_cell**2) + d_cell_next
            d_gate_f = d_cell * previous_cell
            d_previous_cell = d_cell * gate_f
            d_gate_i = d_cell * gate_g
            d_gate_g = d_cell * gate_i
            d_z = np.concatenate(
                [
                    d_gate_i * gate_i * (1.0 - gate_i),
                    d_gate_f * gate_f * (1.0 - gate_f),
                    d_gate_o * gate_o * (1.0 - gate_o),
                    d_gate_g * (1.0 - gate_g**2),
                ],
                axis=1,
            )
            gradients["Wx"] += x_t.T @ d_z
            gradients["Wh"] += previous_hidden.T @ d_z
            gradients["b"] += np.sum(d_z, axis=0)
            d_hidden = d_z @ self.parameters["Wh"].T
            d_cell_next = d_previous_cell
        return loss, gradients

    def fit(
        self,
        x_train: np.ndarray,
        y_train: np.ndarray,
        x_validation: np.ndarray,
        y_validation: np.ndarray,
        learning_rate: float = 0.005,
        batch_size: int = 128,
        max_epochs: int = 40,
        patience: int = 6,
        gradient_clip: float = 5.0,
    ) -> list[dict[str, float]]:
        rng = np.random.default_rng(self.seed + 1)
        first = {name: np.zeros_like(value) for name, value in self.parameters.items()}
        second = {name: np.zeros_like(value) for name, value in self.parameters.items()}
        best = {name: value.copy() for name, value in self.parameters.items()}
        best_loss = np.inf
        stale = 0
        adam_step = 0
        history: list[dict[str, float]] = []
        for epoch in range(1, max_epochs + 1):
            order = rng.permutation(len(x_train))
            training_losses = []
            for start in range(0, len(order), batch_size):
                chosen = order[start : start + batch_size]
                loss, gradients = self._loss_and_gradients(x_train[chosen], y_train[chosen])
                training_losses.append(loss)
                global_norm = np.sqrt(sum(float(np.sum(g**2)) for g in gradients.values()))
                if global_norm > gradient_clip:
                    factor = gradient_clip / (global_norm + 1e-12)
                    gradients = {name: gradient * factor for name, gradient in gradients.items()}
                adam_step += 1
                for name, gradient in gradients.items():
                    first[name] = 0.9 * first[name] + 0.1 * gradient
                    second[name] = 0.999 * second[name] + 0.001 * (gradient**2)
                    corrected_first = first[name] / (1.0 - 0.9**adam_step)
                    corrected_second = second[name] / (1.0 - 0.999**adam_step)
                    self.parameters[name] -= learning_rate * corrected_first / (
                        np.sqrt(corrected_second) + 1e-8
                    )
            validation_prediction = self.predict(x_validation, batch_size=512)
            validation_loss = float(np.mean((validation_prediction - y_validation) ** 2))
            history.append(
                {
                    "epoch": float(epoch),
                    "train_mse_standardized": float(np.mean(training_losses)),
                    "validation_mse_standardized": validation_loss,
                }
            )
            if validation_loss < best_loss - 1e-8:
                best_loss = validation_loss
                best = {name: value.copy() for name, value in self.parameters.items()}
                stale = 0
            else:
                stale += 1
                if stale >= patience:
                    break
        self.parameters = best
        return history

    def predict(self, x: np.ndarray, batch_size: int = 512) -> np.ndarray:
        x = np.asarray(x, dtype=float)
        if len(x) == 0:
            return np.empty((0, self.output_size), dtype=float)
        output = []
        for start in range(0, len(x), batch_size):
            output.append(self._forward(x[start : start + batch_size], cache=False))
        return np.vstack(output)


def regression_metrics(actual: np.ndarray, predicted: np.ndarray, train_scale: float) -> dict[str, float]:
    actual = np.asarray(actual, dtype=float)
    predicted = np.asarray(predicted, dtype=float)
    error = predicted - actual
    mae = float(np.mean(np.abs(error)))
    rmse = float(np.sqrt(np.mean(error**2)))
    denominator = np.abs(actual) + np.abs(predicted)
    smape = float(np.mean(np.where(denominator > 1e-12, 200.0 * np.abs(error) / denominator, 0.0)))
    total = float(np.sum((actual - np.mean(actual)) ** 2))
    r2 = float(1.0 - np.sum(error**2) / total) if total > 1e-12 else float("nan")
    return {
        "mae": mae,
        "rmse": rmse,
        "smape_percent": smape,
        "r2": r2,
        "normalized_rmse_train_sd": rmse / max(float(train_scale), 1e-12),
    }


def empirical_resource_percentiles(
    predicted: np.ndarray, train_values: np.ndarray
) -> np.ndarray:
    predicted = np.asarray(predicted, dtype=float)
    train_values = np.asarray(train_values, dtype=float)
    scores = np.empty_like(predicted, dtype=float)
    for column in range(predicted.shape[1]):
        reference = np.sort(train_values[:, column])
        scores[:, column] = np.searchsorted(reference, predicted[:, column], side="right") / len(reference)
    return np.clip(scores, 0.0, 1.0)


def thesis_hybrid_pressure(predicted: np.ndarray, train_values: np.ndarray) -> np.ndarray:
    percentiles = empirical_resource_percentiles(predicted, train_values)
    weights = np.asarray([0.4, 0.2, 0.2, 0.2], dtype=float)
    return np.clip(percentiles @ weights, 0.0, 1.0)
