from __future__ import annotations

from pathlib import Path

import pandas as pd


def _format(value: object, digits: int = 4) -> str:
    if pd.isna(value):
        return "NA"
    if isinstance(value, (float, int)):
        return f"{float(value):.{digits}f}"
    return str(value)


def generate_markdown(controlled_csv: Path, trace_csv: Path | None, output: Path) -> None:
    controlled = pd.read_csv(controlled_csv)
    grouped = (
        controlled.groupby(["policy", "target_utilization"], as_index=False)
        .agg(
            n=("seed", "count"),
            high_dmr=("high_deadline_miss_ratio", "mean"),
            high_dmr_sd=("high_deadline_miss_ratio", "std"),
            high_response_ms=("high_mean_response", "mean"),
            high_response_sd=("high_mean_response", "std"),
            high_completion=("high_completion_rate", "mean"),
            low_completion=("low_completion_rate", "mean"),
            low_dmr=("low_deadline_miss_ratio", "mean"),
            transitions=("mode_transitions", "mean"),
            service_reduction_ms=("service_reduction", "mean"),
            utilization=("processor_utilization", "mean"),
        )
    )

    lines = [
        "# RT-DASH Reproducible Experiment Report",
        "",
        "## Evidence boundary",
        "",
        "All values in this report were generated by the completed deterministic reference simulator. They are **new project results**, not recovered thesis results and not physical-board measurements. The controlled workload is intentionally constructed to stress deadline-versus-criticality decisions. Results therefore validate the implemented semantics under the declared model; they do not establish universal superiority.",
        "",
        "Deadline-miss ratios exclude right-censored jobs whose deadlines occur after the simulation horizon. High-criticality arrivals trigger Critical Mode immediately; processor-load transitions are based on sampled, smoothed utilization.",
        "",
        "## Controlled experiment design",
        "",
        "- 10 deterministic seeds per load-policy combination.",
        "- Five nominal periodic-load levels: 0.60, 0.80, 0.95, 1.10, and 1.25.",
        "- Five policies: EDF, RMS, RT-DASH, RT-DASH without hysteresis, and RT-DASH without degradation.",
        "- Two emergency bursts per 60 s run. Some three-job bursts are deliberately infeasible within all individual deadlines; this explains the non-zero RT-DASH high-criticality miss ratio.",
        "- Simulation quantum: 5 ms.",
        "",
        "## Controlled results by offered load",
        "",
        grouped.to_markdown(index=False, floatfmt=".4f"),
        "",
        "## Interpretation",
        "",
        "1. **Criticality protection.** In this controlled workload, EDF and RMS frequently delay emergency jobs behind routine work. RT-DASH changes the ordering key at the event release instant, producing much lower high-criticality response times and miss ratios. This is a workload-specific causal result because every policy receives the same task set for each seed/load pair.",
        "2. **Limits of protection.** RT-DASH does not eliminate all high-criticality misses. Emergency bursts containing more mandatory execution than can fit before their deadlines remain infeasible under any uniprocessor policy.",
        "3. **Hysteresis.** Removing hysteresis substantially increases mode transitions, particularly near and above the utilization threshold. The result supports hysteresis as an anti-oscillation mechanism, not as a proof of control-theoretic stability.",
        "4. **Graceful degradation trade-off.** Service reduction preserves completion of low-criticality jobs by omitting declared optional work. Completion alone must therefore be read together with service-reduction and deadline metrics; a reduced-service completion is not equivalent to full-quality execution.",
        "5. **Baseline scope.** EDF and RMS are deterministic reference baselines. The project still requires comparison with a published emergency-first or mixed-criticality algorithm before making a state-of-the-art performance claim.",
        "",
    ]

    if trace_csv and trace_csv.exists():
        trace = pd.read_csv(trace_csv)
        trace_grouped = (
            trace.groupby(["policy", "start_row", "load_scale"], as_index=False)
            .agg(
                high_dmr=("high_deadline_miss_ratio", "mean"),
                high_completion=("high_completion_rate", "mean"),
                overall_completion=("overall_completion_rate", "mean"),
                response_ms=("overall_mean_response", "mean"),
                transitions=("mode_transitions", "mean"),
                utilization=("processor_utilization", "mean"),
            )
        )
        lines.extend(
            [
                "## Trace-derived experiments",
                "",
                "The three contiguous raw OpenSHS windows preserve observed activity order and timestamp spacing. The activity-to-job timing model is newly specified by this completed project because the thesis did not preserve a reproducible mapping. These windows are feasible at the selected scales: all policies complete the released work and no high-criticality deadlines are missed. RT-DASH therefore shows no artificial performance advantage where no overload-management action is needed.",
                "",
                trace_grouped.to_markdown(index=False, floatfmt=".4f"),
                "",
            ]
        )

    lines.extend(
        [
            "## Remaining validation",
            "",
            "- Execute the same protocol on a named FreeRTOS board or a documented emulator/host port.",
            "- Measure real WCETs, context-switch cost, mode-transition overhead, memory footprint, and instrumentation overhead.",
            "- Add a published criticality-aware baseline and longer emergency-duration sweeps.",
            "- Validate application-specific reduced-service variants with domain safety requirements.",
            "",
        ]
    )
    output.write_text("\n".join(lines), encoding="utf-8")
